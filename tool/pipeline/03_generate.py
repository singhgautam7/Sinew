def generate_batch(category: str, subcategory: str, batch_items: List[Dict[str, Any]], batch_index: int) -> Path:
    base_dir = get_base_dir()
    gen_dir = base_dir / "stage" / "generated"
    gen_dir.mkdir(parents=True, exist_ok=True)
    out_file = gen_dir / f"{category}_{subcategory}_b{batch_index:03d}.json"

    if out_file.is_file():
        print(f"Batch file {out_file} already exists. Skipping.")
        return out_file

    config = load_config()
    vocab = load_vocab()
    model_cfg = config.get("models", {}).get("generation", {})
    model_name = model_cfg.get("name", "gemini-2.5-flash")
    temp = model_cfg.get("temperature", 0.2)

    prompt = build_generation_prompt(category, subcategory, batch_items, vocab)
    print(f"Generating {len(batch_items)} records for {category}/{subcategory} (batch {batch_index})...")
    records = call_gemini_json(prompt, model_name=model_name, temperature=temp)

    if records and isinstance(records, list):
        with open(out_file, "w", encoding="utf-8") as f:
            json.dump(records, f, indent=2, ensure_ascii=False)
        print(f"[SAVED] Batch {batch_index} written with {len(records)} records to {out_file}")
    else:
        print(f"[ERROR] Failed to generate valid JSON array for batch {batch_index}")

    return out_file


def main():
    parser = argparse.ArgumentParser(description="Generate exercise records in resumable batches.")
    parser.add_argument("--category", type=str, help="Specific category to generate (e.g. yoga, boxing, strength)")
    parser.add_argument("--subcategory", type=str, help="Specific subcategory")
    parser.add_argument("--batch-size", type=int, default=25, help="Batch size (25-50)")
    parser.add_argument("--limit", type=int, default=0, help="Max items to process")
    args = parser.parse_args()

    base_dir = get_base_dir()
    missing_file = base_dir / "stage" / "plan" / "missing.json"

    if not missing_file.is_file():
        print("Missing stage/plan/missing.json. Run 02_plan.py first.")
        return

    with open(missing_file, "r", encoding="utf-8") as f:
        missing_items = json.load(f)

    if args.category:
        missing_items = [x for x in missing_items if x.get("category") == args.category]
    if args.subcategory:
        missing_items = [x for x in missing_items if x.get("subcategory") == args.subcategory]
    if args.limit > 0:
        missing_items = missing_items[:args.limit]

    print(f"Total planned items to generate: {len(missing_items)}")

    # Group by category and subcategory
    grouped: Dict[str, Dict[str, List[Dict[str, Any]]]] = {}
    for item in missing_items:
        cat = item["category"]
        subcat = item.get("subcategory", "general")
        if cat not in grouped:
            grouped[cat] = {}
        if subcat not in grouped[cat]:
            grouped[cat][subcat] = []
        grouped[cat][subcat].append(item)

    for cat, subcats in grouped.items():
        for subcat, items in subcats.items():
            bsize = args.batch_size
            for i in range(0, len(items), bsize):
                batch_slice = items[i:i + bsize]
                batch_idx = i // bsize + 1
                generate_batch(cat, subcat, batch_slice, batch_idx)


if __name__ == "__main__":
    main()
